/// Where a mark goes on its letter.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Place {
    /// Above, centred. A letter that reaches the cap line gives up a row (two for a ring) for it.
    Above,
    /// Below the baseline, centred.
    Below,
    /// Below the baseline at the right, as an ogonek hangs.
    BelowRight,
}

/// A mark: where it goes and its drawings from narrow to wide. A letter takes the widest that
/// fits it and centres exactly (same parity), else the widest that fits.
pub(super) type MarkDef = (Place, &'static [&'static str]);

