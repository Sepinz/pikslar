//! The drawings of Pikslar Text. Each glyph is its character, the row its drawing starts on and
//! the drawing: rows of `#` (ink) and `.` (paper) separated by `/`, all rows the same width.
//! Rows count from the cap line: 0 to 7 are the capitals' height, 2 to 7 the x-height, 8 and 9
//! the descenders and -1 the row above the capitals, where their marks go.
//!
//! None of these strings reaches the program: `font_text.rs` packs them into column bitmaps
//! while compiling, and checks them (widths, rows, order) at the same time.

/// A glyph's character, first row and drawing.
pub(super) type Art = (char, i8, &'static str);

