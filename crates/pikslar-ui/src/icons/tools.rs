//! Tool icons: 16 by 16, for the tool strip and the context bar's tool badge.

use super::pack::{sheet, words, Art};

/// The tools' icons, in the order of [`TOOL_ART`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ToolIcon {
    Pencil,
    Eraser,
    Fill,
    Picker,
    Line,
    Rectangle,
    Text,
    SelectBox,
    Lasso,
    Wand,
    Move,
    Ellipse,
    Slice,
    ShadingInk,
}

impl ToolIcon {
    pub const ALL: [ToolIcon; TOOLS] = {
        use ToolIcon::*;
        [
            Pencil, Eraser, Fill, Picker, Line, Rectangle, Text, SelectBox, Lasso, Wand, Move,
            Ellipse, Slice, ShadingInk,
        ]
    };

    pub fn art(self) -> Art {
        Art::new(SIZE as i32, &TOOL_ART[self as usize])
    }
}

