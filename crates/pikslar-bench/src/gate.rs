//! Comparing measurements against the committed baseline.

use std::collections::BTreeMap;

/// The most a [`Kind::Percent`] line may read: plan section 9's 1.05.
const PERCENT_TARGET: f64 = 105.0;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// Microseconds. Noisy, so the allowance is generous.
    Micros,
    /// Bytes retained or written. Deterministic.
    Bytes,
    /// Heap allocations. Deterministic.
    Allocs,
    /// One time over another, in percent (M11). Its limit is the plan's target of 105, or a
    /// little over the baseline if that was recorded above it.
    Percent,
}

impl Kind {
    fn tag(self) -> &'static str {
        match self {
            Kind::Micros => "us",
            Kind::Bytes => "bytes",
            Kind::Allocs => "allocs",
            Kind::Percent => "%",
        }
    }

    /// The largest value that still passes.
    fn limit(self, baseline: f64) -> f64 {
        match self {
            Kind::Micros => baseline * 1.30 + 5.0,
            Kind::Bytes => baseline * 1.03,
            Kind::Allocs => baseline * 1.10 + 2.0,
            Kind::Percent => PERCENT_TARGET.max(baseline + 2.0),
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct Metric {
    pub name: String,
    pub kind: Kind,
    pub value: f64,
}

pub fn parse_baseline(text: &str) -> BTreeMap<String, f64> {
    text.lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|line| {
            let mut parts = line.split_whitespace();
            let name = parts.next()?;
            let value = parts.next()?.parse().ok()?;
            Some((name.to_string(), value))
        })
        .collect()
}

pub fn format_baseline(metrics: &[Metric]) -> String {
    let mut out =
        String::from("# Generated by `pikslar-bench update`. Commit changes deliberately.\n");
    for m in metrics {
        out.push_str(&format!("{} {:.1} {}\n", m.name, m.value, m.kind.tag()));
    }
    out
}

/// Returns a description of every metric that got worse, plus metrics missing a baseline.
pub fn regressions(metrics: &[Metric], baseline: &BTreeMap<String, f64>) -> Vec<String> {
    metrics
        .iter()
        .filter_map(|m| match baseline.get(&m.name) {
            None => Some(format!("{}: no baseline (run update)", m.name)),
            Some(&base) if m.value.is_nan() || m.value > m.kind.limit(base) => Some(format!(
                "{}: {:.1} {} is over the limit of {:.1} (baseline {:.1})",
                m.name,
                m.value,
                m.kind.tag(),
                m.kind.limit(base),
                base
            )),
            Some(_) => None,
        })
        .collect()
}

/// Combines two runs of the same workloads, keeping the better reading of each metric.
/// A real slowdown is slow in every run; a busy moment on the machine is not.
pub fn best_of_runs(first: &[Metric], second: &BTreeMap<String, f64>) -> Vec<Metric> {
    first
        .iter()
        .map(|m| Metric {
            value: second.get(&m.name).map_or(m.value, |v| m.value.min(*v)),
            ..m.clone()
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn repeated_runs_forgive_noise_but_not_a_real_slowdown() {
        let base = baseline(100.0);
        let noisy = [metric(Kind::Micros, 200.0)];
        let calm = parse_baseline("m 110 us");
        assert!(regressions(&best_of_runs(&noisy, &calm), &base).is_empty());
        let slower = parse_baseline("m 190 us");
        assert_eq!(regressions(&best_of_runs(&noisy, &slower), &base).len(), 1);
    }

    fn metric(kind: Kind, value: f64) -> Metric {
        Metric {
            name: "m".into(),
            kind,
            value,
        }
    }

    fn baseline(value: f64) -> BTreeMap<String, f64> {
        parse_baseline(&format!("# note\nm {value} us\n"))
    }

    #[test]
    fn baseline_round_trips() {
        let m = metric(Kind::Bytes, 1234.5);
        assert_eq!(parse_baseline(&format_baseline(&[m]))["m"], 1234.5);
    }

    #[test]
    fn small_time_noise_passes_and_real_slowdowns_fail() {
        assert!(regressions(&[metric(Kind::Micros, 125.0)], &baseline(100.0)).is_empty());
        assert_eq!(
            regressions(&[metric(Kind::Micros, 150.0)], &baseline(100.0)).len(),
            1
        );
    }

    #[test]
    fn memory_is_held_to_a_tight_limit() {
        assert!(regressions(&[metric(Kind::Bytes, 1030.0)], &baseline(1000.0)).is_empty());
        assert_eq!(
            regressions(&[metric(Kind::Bytes, 1050.0)], &baseline(1000.0)).len(),
            1
        );
    }

    #[test]
    fn a_ratio_is_held_to_its_target_not_to_a_share_of_itself() {
        let pass = regressions(&[metric(Kind::Percent, 104.9)], &baseline(100.4));
        assert!(pass.is_empty());
        let fail = regressions(&[metric(Kind::Percent, 105.5)], &baseline(100.4));
        assert_eq!(fail.len(), 1);
        // Recorded above the target, it may not drift further.
        assert!(regressions(&[metric(Kind::Percent, 108.0)], &baseline(107.0)).is_empty());
        assert_eq!(
            regressions(&[metric(Kind::Percent, 110.0)], &baseline(107.0)).len(),
            1
        );
    }

    #[test]
    fn improvements_pass() {
        assert!(regressions(&[metric(Kind::Allocs, 1.0)], &baseline(100.0)).is_empty());
    }

    #[test]
    fn a_new_metric_needs_a_baseline() {
        assert_eq!(
            regressions(&[metric(Kind::Micros, 1.0)], &BTreeMap::new()).len(),
            1
        );
    }
}
