/// The glyph of `ch` as three columns of five rows, bit 0 the top row, or `None` for anything
/// outside ASCII. Lower case letters are drawn as capitals.
pub(crate) fn tiny_columns(ch: char) -> Option<([u16; 5], usize)> {
    let ch = ch.to_ascii_uppercase();
    let (_, rows) = TINY.iter().find(|&&(c, _)| c == ch)?;
    let mut columns = [0u16; 5];
    for (row, line) in rows.iter().enumerate() {
        for (column, cell) in line.bytes().enumerate() {
            if cell == b'#' {
                columns[column] |= 1 << row;
            }
        }
    }
    Some((columns, 3))
}

#[cfg(test)]
pub(crate) fn tiny_chars() -> impl Iterator<Item = char> {
    TINY.iter().map(|&(c, _)| c)
}

#[cfg(test)]
pub(crate) fn tiny_rows(ch: char) -> Option<[&'static str; 5]> {
    TINY.iter().find(|&&(c, _)| c == ch).map(|&(_, rows)| rows)
}
