//! The tiny 3x5 font: printable ASCII for labels and small heads-up text.
//!
//! Where it came from: every glyph here was drawn for Pikslar, one pattern at a time, as three
//! columns of five rows. It is not copied or converted from any font, font file or bitmap table;
//! nothing was consulted while drawing it, and so it carries no one else's licence. A glyph this
//! small has few sensible shapes, so some look like those of other tiny faces, as the letter T
//! looks like a T everywhere. Lower case letters share the shapes of the capitals, as faces this
//! small usually must: three columns cannot tell them apart.
//!
//! Each glyph is five strings of three characters, `#` for ink, in order from the top row.

